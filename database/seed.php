    ['Советы',    'Практические советы для владельцев кроликов'],
];

$categoryBySlug = [];
foreach ($categories as [$name, $desc]) {
    $slug = Slug::fromString($name);
    $pdo->prepare(
        'INSERT INTO categories (slug, name, description) VALUES (?, ?, ?)
         ON DUPLICATE KEY UPDATE name = VALUES(name), description = VALUES(description)'
    )->execute([$slug, $name, $desc]);
    $categoryBySlug[$slug] = (int) $pdo->query(
        'SELECT id FROM categories WHERE slug = ' . $pdo->quote($slug)
    )->fetchColumn();
}

// Удалить категории, которых нет в новом списке
$keepSlugs = array_keys($categoryBySlug);
$keepPlaceholders = implode(',', array_fill(0, count($keepSlugs), '?'));
$stmt = $pdo->prepare("DELETE FROM categories WHERE slug NOT IN ({$keepPlaceholders})");
$stmt->execute($keepSlugs);

echo 'Categories: ' . count($categoryBySlug) . "\n";

