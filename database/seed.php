$baseTime = time() - 86400 * count($articles);
$insertArticle = $pdo->prepare(
    'INSERT INTO articles (slug, image, title, description, body, views, published_at) VALUES (?, ?, ?, ?, ?, ?, ?)
     ON DUPLICATE KEY UPDATE image = VALUES(image), title = VALUES(title), description = VALUES(description),
     body = VALUES(body), published_at = VALUES(published_at)'
);
$deleteLinks = $pdo->prepare('DELETE FROM article_categories WHERE article_id = ?');
$insertLink = $pdo->prepare('INSERT IGNORE INTO article_categories (article_id, category_id) VALUES (?, ?)');

foreach ($articles as $i => $art) {
    $publishedAt = date('Y-m-d H:i:s', $baseTime + $i * 86400);
    $imagePath = 'images/' . $art['slug'] . '.jpg';

    $insertArticle->execute([
        $art['slug'], $imagePath, $art['title'], $art['desc'], $art['body'],
        rand(10, 1000), $publishedAt,
    ]);

    $articleId = (int) $pdo->query(
        'SELECT id FROM articles WHERE slug = ' . $pdo->quote($art['slug'])
    )->fetchColumn();

    $deleteLinks->execute([$articleId]);
    foreach ($art['cats'] as $catSlug) {
        if (isset($categoryBySlug[$catSlug])) {
            $insertLink->execute([$articleId, $categoryBySlug[$catSlug]]);
        }
    }
}

// Удалить статьи, которых нет в новом списке
$keepArticleSlugs = array_column($articles, 'slug');
$keepArticlePlaceholders = implode(',', array_fill(0, count($keepArticleSlugs), '?'));
$stmt = $pdo->prepare("DELETE FROM articles WHERE slug NOT IN ({$keepArticlePlaceholders})");
$stmt->execute($keepArticleSlugs);

echo 'Articles: ' . count($articles) . "\n";

// Очистка кеша после сидинга
